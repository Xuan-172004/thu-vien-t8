async function seedDatabase() {
    console.log('🚀 [SEEDER] Starting full library database seed...');
    
    try {
        await sequelize.authenticate();
        console.log('✅ [SEEDER] Database connection authenticated successfully.');

        // 1. Clear Old Data with foreign keys temporarily disabled
        console.log('🧹 [SEEDER] Cleaning old book copies, books, warehouses, shelves, digital docs and categories...');
        await sequelize.query('SET FOREIGN_KEY_CHECKS = 0;');
        
        await sequelize.query('DELETE FROM digital_doc_purchases;');
        await sequelize.query('DELETE FROM rental_items;');
        await sequelize.query('DELETE FROM book_copies;');
        await sequelize.query('DELETE FROM books;');
        await sequelize.query('DELETE FROM digital_documents;');
        await sequelize.query('DELETE FROM shelves;');
        await sequelize.query('DELETE FROM warehouses;');
        await sequelize.query('DELETE FROM categories;');

        await sequelize.query('SET FOREIGN_KEY_CHECKS = 1;');
        console.log('✨ [SEEDER] Old mock data cleaned successfully.');

        // 2. Insert Warehouses & Shelves
        console.log('📦 [SEEDER] Creating Warehouses...');
        await Warehouse.bulkCreate(warehousesData);

        console.log('🗄 [SEEDER] Creating Shelves...');
        await Shelf.bulkCreate(shelvesData);

        // 3. Insert Categories
        console.log('📑 [SEEDER] Creating Categories...');
        await Category.bulkCreate(categoriesData);

        // 4. Insert Books & Physical Copies
        console.log('📚 [SEEDER] Inserting 80+ Books and 300+ Physical Book Copies...');
        let bookIndex = 1;
        let copyIndex = 1;

        for (const [catId, books] of Object.entries(booksByCategory)) {
            const catObj = categoriesData.find(c => c.id === catId);
            const warehouseId = catId === 'cong-nghe' || catId === 'khoa-hoc' ? 'wh-cntt' 
                              : catId === 'kinh-te' ? 'wh-kinhte' 
                              : 'wh-thamkhao';

            const shelfId = catId === 'cong-nghe' ? 'sh-cntt-01'
                          : catId === 'khoa-hoc' ? 'sh-cntt-02'
                          : catId === 'kinh-te' ? 'sh-eco-01'
                          : catId === 'ky-nang' ? 'sh-ref-01'
                          : 'sh-ref-02';

            for (const b of books) {
                const bookId = `b${bookIndex++}`;
                const totalCopies = 4;
                const availableCopies = 3;

                // Create Book
                const createdBook = await Book.create({
                    id: bookId,
                    title: b.title,
                    slug: b.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, ''),
                    author: b.author,
                    categoryId: catId,
                    categoryName: catObj ? catObj.name : 'Chuyên ngành',
                    publisher: b.publisher,
                    year: b.year,
                    isbn: b.isbn,
                    ddcCode: b.ddcCode,
                    pages: b.pages,
                    language: 'Tiếng Việt / Tiếng Anh',
                    cover: b.cover,
                    images: [b.cover],
                    thumbnails: [b.cover],
                    rating: Number((4.7 + (Math.random() * 0.3)).toFixed(1)),
                    reviewsCount: Math.floor(25 + Math.random() * 200),
                    rentCount: Math.floor(50 + Math.random() * 400),
                    price7Days: 0,
                    price14Days: 0,
                    price30Days: 0,
                    deposit: b.deposit || 100000,
                    marketPrice: (b.deposit || 100000) + 30000,
                    availabilityStatus: 'available',
                    totalCopies: totalCopies,
                    availableCopies: availableCopies,
                    room: warehouseId === 'wh-cntt' ? 'Phòng 201' : warehouseId === 'wh-kinhte' ? 'Phòng 301' : 'Phòng 102',
                    floor: warehouseId === 'wh-cntt' ? 'Tầng 2' : warehouseId === 'wh-kinhte' ? 'Tầng 3' : 'Tầng 1',
                    shelf: shelfId,
                    location: 'Thư viện Trung tâm',
                    condition: 'Rất tốt (95%)',
                    summary: b.description,
                    description: b.description,
                    isFeatured: (bookIndex % 4 === 0),
                    isVisible: true,
                });

                // Create Physical Copies (DKCB)
                for (let c = 1; c <= totalCopies; c++) {
                    const isAvailable = c <= availableCopies;
                    const dkcbFormatted = `DKCB-2026-${String(copyIndex).padStart(4, '0')}`;
                    await BookCopy.create({
                        copyId: `CP-${bookId}-${c}`,
                        dkcbCode: dkcbFormatted,
                        bookId: createdBook.id,
                        warehouseId: warehouseId,
                        shelfId: shelfId,
                        status: isAvailable ? 'Available' : 'Rented',
                        statusText: isAvailable ? 'Có sẵn trong kho' : 'Đang mượn',
                        physicalCondition: c === 1 ? 'new' : 'good',
                        conditionText: c === 1 ? 'Mới 100%' : 'Rất tốt (95%)',
                        location: `Kệ ${shelfId.toUpperCase()} - Vị trí ${c}`,
                        note: 'Sẵn sàng phục vụ bạn đọc',
                    });
                    copyIndex++;
                }
            }

            // Update category count
            await Category.update(
                { count: books.length },
                { where: { id: catId } }
            );
        }

        // 5. Insert Digital Theses & Documents
        console.log('🎓 [SEEDER] Inserting Digital Documents & Graduation Theses...');
        await DigitalDocument.bulkCreate(digitalThesesData);

        console.log(`\n🎉 [SEEDER SUCCESS] Library database seeded successfully!`);
        console.log(`- Categories created: ${categoriesData.length}`);
        console.log(`- Books created: ${bookIndex - 1}`);
        console.log(`- Physical copies created: ${copyIndex - 1}`);
        console.log(`- Digital Theses created: ${digitalThesesData.length}\n`);

    } catch (error) {
        console.error('❌ [SEEDER ERROR] Seeding failed:', error);
        process.exit(1);
    }
}

// Auto execute when run directly
if (require.main === module) {
    seedDatabase().then(() => {
        process.exit(0);
    });
}

module.exports = { seedDatabase };
